const deferred = () => { let resolve; const promise = new Promise(done => { resolve = done; }); return { promise, resolve }; };
const flush = async () => { for (let i = 0; i < 10; i++) await Promise.resolve(); };
const TRACK = 'spotify:track:fixture';
const sourceInfo = () => ({ youtubeVideoId: 'video-a', captionStartTime: 5, isAutoGenerated: true, skipSegments: [] });

function harness({ helper = false } = {}) {
  const events = new Map(), writes = [], seeks = [], pauses = [], hooks = [], playerListeners = [];
  let cursor = 0, remoteCalls = 0;
  const window = {
    ivLyricsActiveCommunityVideoInfo: { ...sourceInfo(), trackUri: TRACK },
    Spicetify: { Player: { addEventListener: (...args) => playerListeners.push(args) } },
    addEventListener(name, callback) { if (!events.has(name)) events.set(name, new Set()); events.get(name).add(callback); },
    removeEventListener(name, callback) { events.get(name)?.delete(callback); },
    dispatchEvent(event) { for (const callback of events.get(event.type) || []) callback(event); },
  };
  const localVideo = { currentTime: 15, duration: 300, paused: true, pause: () => pauses.push('helper'), play: () => Promise.resolve() };
  const player = { getPlayerState: () => 2, getCurrentTime: () => 15, getDuration: () => 300,
    seekTo: time => seeks.push(time), pauseVideo: () => pauses.push('youtube'), playVideo() {} };
  const context = vm.createContext({
    window, console: { error() {} },
    react: { memo: component => component },
    useState(initial) { const i = cursor++; if (!(i in hooks)) hooks[i] = typeof initial === 'function' ? initial() : initial; return [hooks[i], value => { hooks[i] = value; }]; },
    useRef(value) { const i = cursor++; return hooks[i] ||= { current: value }; },
    useEffect: callback => callback(),
    Utils: {
      updateSelectedVideoSyncOffset: async (...args) => writes.push(args),
      mapVideoTimeWithSkipSegments: time => time,
      submitCommunityVideo() { remoteCalls++; },
    },
    Spicetify: { Player: { getProgress: () => 20000 } }, CONFIG: { visual: {} },
    CustomEvent: class { constructor(type, options) { this.type = type; this.detail = options.detail; } },
    trackUri: TRACK, videoInfo: sourceInfo(), useHelper: helper, isPlayerReady: true, isPlaying: false,
    firstLyricTimeRef: { current: 10000 }, trackOffsetMsRef: { current: 0 },
    videoRef: { current: localVideo }, playerRef: { current: player },
    youtubeHoldStateRef: { current: { isHolding: false, primePending: false } },
    videoDriftStateRef: { current: null },
  });
  vm.runInContext(slice(options, 'const COMMUNITY_VIDEO_SYNC_MAX_SECONDS', '\nconst TrackSyncAdjustPill') +
    '\nglobalThis.api = { useCurrentVideoSync, queueCommunityVideoSyncWrite };', context);
  vm.runInContext(video.slice(0, video.indexOf('const disableYouTubeCaptions')), context);
  vm.runInContext(slice(video, '    // Offset taps update the timeline', '    const reportVideoBackgroundStatus'), context);
  const controls = context.api.useCurrentVideoSync(TRACK);
  return { context, window, controls, seeks, writes, localVideo, playerListeners,
    remoteCalls: () => remoteCalls };
}

for (const helper of [false, true]) {
  test(`${helper ? 'helper' : 'iframe'}: a 10ms tap immediately seeks paused playback without changing the video source`, async () => {
    const h = harness({ helper });
    h.controls.handleStep(10); await flush();
    const actual = helper ? h.localVideo.currentTime : h.seeks[0];
    assert.ok(Math.abs(actual - 15.01) < .000001);
    assert.equal(h.context.videoInfo.captionStartTime, 5, 'source identity stays stable; no player reload');
    assert.equal(h.window.ivLyricsActiveCommunityVideoInfo.captionStartTime, 5.01);
    assert.equal(h.writes[0][0], TRACK);
    assert.equal(h.remoteCalls(), 0, 'quick adjustments never publish to the community API');
    assert.deepEqual(h.playerListeners, [], 'no implicit song-change publication listener');
  });
}

test('stale track/video events cannot seek the active player', () => {
  const h = harness();
  for (const detail of [{ trackUri: 'other', youtubeVideoId: 'video-a' }, { trackUri: TRACK, youtubeVideoId: 'other' }]) {
    h.window.dispatchEvent({ type: 'ivLyrics:community-video-start-changed', detail });
  }
  assert.deepEqual(h.seeks, []);
  h.window.ivLyricsActiveCommunityVideoInfo = null;
  h.controls.handleStep(10);
  assert.deepEqual(h.seeks, []);
});

