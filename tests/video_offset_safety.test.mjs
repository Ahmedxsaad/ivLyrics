test('rapid steps are serialized and coalesced to the latest local anchor', async () => {
  const h = harness(), first = deferred(), writes = [];
  h.context.Utils.updateSelectedVideoSyncOffset = async (_uri, info) => {
    writes.push(info.captionStartTime); if (writes.length === 1) await first.promise;
  };
  const run = h.context.api.queueCommunityVideoSyncWrite(TRACK, { ...sourceInfo(), captionStartTime: 1 });
  h.context.api.queueCommunityVideoSyncWrite(TRACK, { ...sourceInfo(), captionStartTime: 2 });
  h.context.api.queueCommunityVideoSyncWrite(TRACK, { ...sourceInfo(), captionStartTime: 3 });
  assert.deepEqual(writes, [1]);
  first.resolve(); await run;
  assert.deepEqual(writes, [1, 3]);
  assert.equal(h.remoteCalls(), 0);
});

function atomicStore(existing) {
  const request = {}, puts = [];
  let transaction, closed = 0;
  const db = { transaction(_name, mode) {
    assert.equal(mode, 'readwrite');
    transaction = { objectStore: () => ({ get: () => request, put: value => puts.push(value) }) };
    return transaction;
  }, close() { closed++; } };
  const api = vm.runInNewContext('({' + slice(utils, '  async updateSelectedVideoSyncOffset(', '  /**\n   * 오래된 선택 영상 정리') + '})');
  api._openSelectedVideoDB = async () => db;
  return { api, puts, request, closed: () => closed,
    commit() { request.result = existing; request.onsuccess(); transaction.oncomplete(); },
    abort() { transaction.onabort(); },
  };
}

test('an atomic offset update cannot overwrite a subsequently selected video', async () => {
  const h = atomicStore({ trackUri: TRACK, youtubeVideoId: 'video-b', captionStartTime: 99 });
  const pending = h.api.updateSelectedVideoSyncOffset(TRACK, { ...sourceInfo(), captionStartTime: 5.1 });
  await flush(); h.commit();
  assert.equal(await pending, false); assert.deepEqual(h.puts, []); assert.equal(h.closed(), 1);
});

test('a matching local video retains its metadata, commits the exact anchor, and closes its DB', async () => {
  const h = atomicStore({ ...sourceInfo(), custom: 'keep' });
  const pending = h.api.updateSelectedVideoSyncOffset(TRACK, { ...sourceInfo(), captionStartTime: 0 });
  await flush(); h.commit();
  assert.equal(await pending, true); assert.equal(h.puts[0].captionStartTime, 0);
  assert.equal(h.puts[0].custom, 'keep'); assert.equal(h.puts[0].isAutoGenerated, false);
  assert.equal(h.closed(), 1);
});

test('aborted local writes reject instead of reporting a successful save', async () => {
  const h = atomicStore(sourceInfo());
  const pending = h.api.updateSelectedVideoSyncOffset(TRACK, { ...sourceInfo(), captionStartTime: 1 });
  await flush(); h.abort();
  await assert.rejects(pending, /transaction failed/); assert.equal(h.closed(), 1);
});
