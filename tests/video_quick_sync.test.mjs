// Minimal hooks: renders synchronously, runs effects after each render and
// re-renders on state changes, enough to drive one component.
function createEnvironment() {
    const storage = new Map();
    const window = new EventTarget();
    window.setTimeout = () => 0;
    window.clearTimeout = () => { };
    const toasts = [];
    const submissions = [];
    const env = {
        window,
        storage,
        toasts,
        submissions,
        submitError: null,
        StorageManager: {
            getItem: (key) => storage.get(key) ?? null,
            setItem: (key, value) => storage.set(key, String(value)),
        },
        IvLyricsToolbarIcon: ({ name }) => ({ type: "svg", props: { "data-icon": name }, children: [] }),
        Utils: {
            extractTrackId: (uri) => uri.split(":")[2],
            getTrackSyncOffset: async () => 0,
            setTrackSyncOffset: async () => true,
            submitCommunityVideo: async (...args) => {
                submissions.push(args);
                if (env.submitError) throw env.submitError;
                return { success: true };
            },
        },
        Toast: {
            success: (message) => toasts.push(["success", message]),
            error: (message) => toasts.push(["error", message]),
        },
        I18n: { t: (key) => key },
        CustomEvent,
        console,
        Math,
    };
    return env;
}

function loadHelpers(env = createEnvironment()) {
    const context = vm.createContext(env);
    vm.runInContext(`${videoHelpers}\nglobalThis.__helpers = { getVideoSyncAdjustmentMs, setVideoSyncAdjustmentMs, getSharedVideoStartTime, createVideoDriftState, planVideoDriftCorrection, VIDEO_SYNC_ADJUSTMENT_LIMIT };`, context);
    return { env, ...context.__helpers };
}

function mountPill(env, { trackUri = TRACK, lyricsAdjustable = true, videoTrackUri = trackUri } = {}) {
    const hooks = [];
    let cursor = 0;
    let pendingEffects = [];
    let tree = null;
    const render = () => {
        cursor = 0;
        pendingEffects = [];
        tree = env.TrackSyncAdjustPill({ trackUri, lyricsAdjustable, videoTrackUri });
        const effects = pendingEffects;
        pendingEffects = [];
        effects.forEach((run) => run());
    };
    Object.assign(env, {
        react: {
            createElement: (type, props, ...children) => ({ type, props: props || {}, children: children.flat(Infinity).filter((child) => child !== null && child !== undefined && child !== false) }),
            memo: (component) => component,
        },
        useState: (initial) => {
            const index = cursor++;
            if (!(index in hooks)) hooks[index] = { value: typeof initial === "function" ? initial() : initial };
            const slot = hooks[index];
            return [slot.value, (next) => {
                const value = typeof next === "function" ? next(slot.value) : next;
                if (Object.is(value, slot.value)) return;
                slot.value = value;
                render();
            }];
        },
        useRef: (value) => {
            const index = cursor++;
            if (!(index in hooks)) hooks[index] = { current: value };
            return hooks[index];
        },
        useEffect: (effect, deps) => {
            const index = cursor++;
            const previous = hooks[index];
            if (previous && deps && deps.every((dep, i) => Object.is(dep, previous.deps[i]))) return;
            pendingEffects.push(() => {
                previous?.cleanup?.();
                hooks[index] = { deps, cleanup: effect() };
            });
        },
    });
    const context = vm.createContext(env);
    vm.runInContext(`${videoHelpers}\n${pillSource}\nglobalThis.TrackSyncAdjustPill = TrackSyncAdjustPill;`, context);
    env.TrackSyncAdjustPill = context.TrackSyncAdjustPill;
    render();
    const nodes = (node, out = []) => {
        if (node && typeof node === "object") {
            out.push(node);
            node.children?.forEach((child) => nodes(child, out));
        }
        return out;
    };
    return {
        get tree() { return tree; },
        buttons: () => nodes(tree).filter((node) => node.type === "button"),
        modeButton: (icon) => nodes(tree).find((node) => node.type === "button"
            && node.children.some((child) => child?.props?.name === icon)),
        text: (node) => nodes(node).flatMap((child) => child.children.filter((value) => typeof value === "string")).join(""),
        context,
    };
}

const activate = (env, videoInfo, trackUri = TRACK, { playerReady = true } = {}) => {
    env.window.ivLyricsActiveCommunityVideoInfo = videoInfo ? { trackUri, ...videoInfo, playerReady } : null;
    env.window.dispatchEvent(new CustomEvent("ivLyrics:active-video-changed", { detail: { trackUri } }));
};

test("a nudge is kept per song video and stops applying once its start point changes", () => {
    const { env, getVideoSyncAdjustmentMs, setVideoSyncAdjustmentMs } = loadHelpers();
    const events = [];
    env.window.addEventListener("ivLyrics:video-sync-adjusted", (event) => events.push({ ...event.detail }));
    assert.equal(setVideoSyncAdjustmentMs(TRACK, autoVideo, 1250), 1250);
    assert.equal(getVideoSyncAdjustmentMs(TRACK, autoVideo), 1250);
    assert.equal(getVideoSyncAdjustmentMs(TRACK, { ...autoVideo, captionStartTime: null }), 1250,
        "an automatic 0 start is the same unknown start as null");
    assert.equal(getVideoSyncAdjustmentMs(TRACK, { ...autoVideo, captionStartTime: 12.4 }), 0,
        "a new start point (e.g. the shared one) already includes the nudge");
    assert.equal(getVideoSyncAdjustmentMs(TRACK, { ...autoVideo, youtubeVideoId: "other123456" }), 0);
    assert.deepEqual(events, [{ trackUri: TRACK, videoId: "PsO6ZnUZI0g", offsetMs: 1250 }]);
    assert.equal(setVideoSyncAdjustmentMs(TRACK, autoVideo, 999_999), 120_000, "nudges are bounded");
    setVideoSyncAdjustmentMs(TRACK, autoVideo, 0);
    assert.equal(env.storage.get("ivLyrics:video-sync-adjustments"), "{}", "a reset removes the entry");
});

test("only the most recent song videos keep their nudges", () => {
    const { env, getVideoSyncAdjustmentMs, setVideoSyncAdjustmentMs, VIDEO_SYNC_ADJUSTMENT_LIMIT } = loadHelpers();
    for (let index = 0; index <= VIDEO_SYNC_ADJUSTMENT_LIMIT; index++) {
        setVideoSyncAdjustmentMs(`spotify:track:t${index}`, autoVideo, 250);
    }
    assert.equal(Object.keys(JSON.parse(env.storage.get("ivLyrics:video-sync-adjustments"))).length, VIDEO_SYNC_ADJUSTMENT_LIMIT);
    assert.equal(getVideoSyncAdjustmentMs("spotify:track:t0", autoVideo), 0);
    assert.equal(getVideoSyncAdjustmentMs(`spotify:track:t${VIDEO_SYNC_ADJUSTMENT_LIMIT}`, autoVideo), 250);
});

test("shares the start point that matches what the user sees", () => {
    const { getSharedVideoStartTime } = loadHelpers();
    // Unknown start: the video was assumed to begin with the song.
    assert.equal(getSharedVideoStartTime(autoVideo, 12.3, 2500), 14.8);
    // Known start: moved by the nudge.
    assert.equal(getSharedVideoStartTime({ ...autoVideo, captionStartTime: 37 }, 12.3, -750), 36.3);
    assert.equal(getSharedVideoStartTime(autoVideo, null, 2500), null, "needs synced lyrics");
    assert.equal(getSharedVideoStartTime(autoVideo, 1, -2000), null, "cannot start before the video");
});

test("a nudge moves the video at once instead of waiting for steady drift", () => {
    const { createVideoDriftState, planVideoDriftCorrection } = loadHelpers();
    const state = createVideoDriftState();
    state.lastSeekAt = -10_000;
    state.seekRequested = true;
    assert.deepEqual({ ...planVideoDriftCorrection(state, { currentTime: 30, targetTime: 30.25, now: 0, isPlaying: true, isSteady: true }) },
        { type: "seek", time: 30.25 });
    assert.deepEqual({ ...planVideoDriftCorrection(state, { currentTime: 30.25, targetTime: 30.25, now: 10, isPlaying: true, isSteady: true }) },
        { type: "none" });
});

const pressKey = (env, code, extra = {}) => {
    const event = new Event("keydown", { cancelable: true });
    const fields = { code, shiftKey: false, altKey: false, ctrlKey: false, metaKey: false, target: { tagName: "DIV" }, ...extra };
    for (const [name, value] of Object.entries(fields)) Object.defineProperty(event, name, { value });
    env.window.dispatchEvent(event);
    return event;
};
const currentValue = (pill) => pill.text(pill.buttons().find((button) => button.props.className === "lyrics-track-sync-value")
    .children.find((child) => child.props?.className === "lyrics-track-sync-value-current"));

test("without a video the sync pill stays the lyric pill, with no switch", () => {
    const env = createEnvironment();
    const pill = mountPill(env);
    assert.ok(pill.tree);
    assert.equal(pill.modeButton("communityVideo"), undefined);
    assert.equal(pill.tree.props.className, "lyrics-track-sync-pill");
    assert.deepEqual(pill.buttons().filter((button) => button.props.className === "lyrics-track-sync-step").map(pill.text),
        ["−100ms", "−50ms", "−10ms", "+10ms", "+50ms", "+100ms"]);
    assert.equal(pressKey(env, "BracketRight").defaultPrevented, false, "the keys need a video");
});

test("the switch turns the same pill into video timing, saved for the song's video", async () => {
    const env = createEnvironment();
    const pill = mountPill(env);
    await new Promise((resolve) => setTimeout(resolve)); // the saved lyric offset loads asynchronously
    activate(env, autoVideo);
    assert.ok(pill.modeButton("synced") && pill.modeButton("communityVideo"), "Lyrics/Video switch while a video plays");
    assert.equal(pill.modeButton("synced").props["aria-pressed"], "true", "lyrics stay selected first");

    pill.modeButton("communityVideo").props.onClick();
    assert.match(pill.tree.props.className, /is-video-mode/);
    const byLabel = (label) => pill.buttons().find((button) => pill.text(button) === label);
    assert.ok(["−2s", "−0.5s", "−0.1s", "+0.1s", "+0.5s", "+2s"].every(byLabel), "video steps in seconds");
    byLabel("+0.5s").props.onClick();
    byLabel("+2s").props.onClick();
    assert.equal(currentValue(pill), "+2.5s");

    pressKey(env, "BracketLeft");
    pressKey(env, "BracketLeft", { shiftKey: true });
    assert.equal(pressKey(env, "BracketRight", { target: { tagName: "INPUT" } }).defaultPrevented, false, "typing is ignored");
    assert.equal(currentValue(pill), "+0.4s", "+2.5 s, then −0.1 s and −2 s from the keys");
    const stored = JSON.parse(env.storage.get("ivLyrics:video-sync-adjustments"));
    assert.deepEqual(stored["0j2T0R9dR9qdJYsB7ciXhf:PsO6ZnUZI0g"], { offsetMs: 400, base: null });

    pill.modeButton("synced").props.onClick();
    assert.equal(currentValue(pill), "0ms", "switching back shows the lyric offset again");
    byLabel("+50ms").props.onClick();
    assert.equal(JSON.parse(env.storage.get("ivLyrics:video-sync-adjustments"))["0j2T0R9dR9qdJYsB7ciXhf:PsO6ZnUZI0g"].offsetMs, 400,
        "lyric steps never touch the video timing");

    pressKey(env, "BracketRight");
    assert.match(pill.tree.props.className, /is-video-mode/, "a video key shows the video side");
    assert.equal(currentValue(pill), "+0.5s");

    activate(env, null);
    assert.equal(pill.modeButton("communityVideo"), undefined, "the switch leaves with the video");
});

test("video timing only appears for a chosen video background that is showing", async () => {
    const env = createEnvironment();
    const pill = mountPill(env);
    await new Promise((resolve) => setTimeout(resolve));
    activate(env, autoVideo, TRACK, { playerReady: false });
    assert.equal(pill.modeButton("communityVideo"), undefined, "not while the video loads or after it failed");
    activate(env, autoVideo);
    assert.ok(pill.modeButton("communityVideo"));

    // Another background is chosen: index.js passes no video track.
    const other = createEnvironment();
    const lyricsOnly = mountPill(other, { videoTrackUri: null });
    activate(other, autoVideo);
    assert.equal(lyricsOnly.modeButton("communityVideo"), undefined);
    assert.equal(pressKey(other, "BracketRight").defaultPrevented, false, "and the keys do nothing");
});

test("a video without synced lyrics gets a video-only pill", () => {
    const env = createEnvironment();
    const pill = mountPill(env, { lyricsAdjustable: false });
    assert.equal(pill.tree, null, "hidden without a video");
    activate(env, autoVideo);
    assert.match(pill.tree.props.className, /is-video-mode/);
    assert.equal(pill.modeButton("synced"), undefined, "no lyric side to switch to");
    activate(env, null);
    assert.equal(pill.tree, null);
});

test("share submits the visible video timing as the community start point", async () => {
    const env = createEnvironment();
    env.window.ivLyrics_firstLyricTime = 12_300;
    const pill = mountPill(env);
    activate(env, autoVideo);
    pill.modeButton("communityVideo").props.onClick();
    const share = () => pill.buttons().find((button) => button.props.className === "lyrics-track-sync-share");
    assert.equal(share(), undefined, "nothing to share without a nudge");

    pill.buttons().find((button) => pill.text(button) === "+2s").props.onClick();
    await share().props.onClick();
    assert.deepEqual(env.submissions, [[TRACK, "PsO6ZnUZI0g", "Kanye West - Stronger", 14.3, []]]);
    assert.deepEqual(env.toasts, [["success", "videoSync.shared"]]);

    env.submitError = new Error("login required");
    await share().props.onClick();
    assert.deepEqual(env.toasts.at(-1), ["error", "login required"]);

    env.window.ivLyrics_firstLyricTime = null;
    await share().props.onClick();
    assert.deepEqual(env.toasts.at(-1), ["error", "videoSync.cannotShare"]);
    assert.equal(env.submissions.length, 2);

    pill.modeButton("synced").props.onClick();
    assert.equal(share(), undefined, "share belongs to the video side");
});
