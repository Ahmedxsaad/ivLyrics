import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import vm from "node:vm";

const source = readFileSync(new URL("../VideoMatch.js", import.meta.url), "utf8");
const context = vm.createContext({ window: {} });
vm.runInContext(source, context);
const VideoMatch = context.window.ivLyricsVideoMatch;

const goosebumps = { title: "goosebumps", artists: ["Travis Scott"], durationMs: 243_000, isrc: "USSM11607576" };
const blindingLights = { title: "Blinding Lights", artists: ["The Weeknd"], durationMs: 200_040, isrc: "USUG11904206" };
const autoMatch = { isAutoGenerated: true };

test("accepts an official music video with an intro", () => {
    const result = VideoMatch.assess(blindingLights, {
        ...autoMatch,
        title: "The Weeknd - Blinding Lights (Official Video)",
        channel: "TheWeekndVEVO",
        durationSeconds: 261,
    });
    assert.equal(result.verdict, "match");
});

test("rejects another song's video, even across scripts once its length disagrees", () => {
    const arabicVideo = { ...autoMatch, title: "عمرو دياب - تملي معاك" };
    assert.equal(VideoMatch.assess(goosebumps, { ...arabicVideo, durationSeconds: 190 }).verdict, "mismatch");
    // Different scripts cannot be compared by title alone, so it is kept until the length is known.
    assert.equal(VideoMatch.assess(goosebumps, arabicVideo).verdict, "uncertain");
    assert.equal(VideoMatch.assess(goosebumps, { ...arabicVideo, isrc: "EGA011500001" }).verdict, "mismatch");
    assert.equal(VideoMatch.assess(goosebumps, { ...autoMatch, title: "Dua Lipa - Levitating (Official Music Video)" }).verdict, "mismatch");
});

test("keeps a native-script title of the right song", () => {
    const track = { title: "夜に駆ける", artists: ["YOASOBI"], durationMs: 261_000 };
    const result = VideoMatch.assess(track, { ...autoMatch, title: "YOASOBI「夜に駆ける」 Official Music Video", durationSeconds: 276 });
    assert.equal(result.verdict, "match");
});

test("ignores Spotify version suffixes and featured artists in the title", () => {
    const track = { title: "Under Pressure - Remastered 2011", artists: ["Queen", "David Bowie"], durationMs: 248_000 };
    assert.equal(VideoMatch.getCoreTitle("Song (feat. Someone) - Radio Edit"), "Song");
    assert.equal(VideoMatch.assess(track, { ...autoMatch, title: "Queen & David Bowie - Under Pressure (Official Video)" }).verdict, "match");
});

test("prefers the studio version over a live or cover upload", () => {
    const live = { ...autoMatch, youtubeVideoId: "live1234567", title: "The Weeknd - Blinding Lights (Live at the Grammys)" };
    const official = { ...autoMatch, youtubeVideoId: "4NRXx6U8ABQ", title: "The Weeknd - Blinding Lights (Official Video)" };
    assert.equal(VideoMatch.assess(blindingLights, live).verdict, "weak");
    assert.equal(VideoMatch.pickCandidate(blindingLights, [live, official]).video, official);
    assert.equal(VideoMatch.pickCandidate(blindingLights, [live]).video, live, "an altered version beats no video");
    // A live album track may use its live video.
    assert.equal(VideoMatch.findAlteredVersionKeywords("Blinding Lights - Live", live.title).length, 0);
});

test("never second-guesses a chosen or community-curated video by its title", () => {
    const fanEdit = { title: "night drive aesthetic edit", isAutoGenerated: false, communityEntryId: 12 };
    assert.equal(VideoMatch.assess(goosebumps, fanEdit).verdict, "uncertain");
    assert.equal(VideoMatch.assess(goosebumps, { title: "anything", userChosen: true }).verdict, "match");
});

test("treats loops and clips by their length", () => {
    assert.equal(VideoMatch.assess(blindingLights, { ...autoMatch, title: "Blinding Lights 1 hour", durationSeconds: 3600 }).verdict, "weak");
    assert.equal(VideoMatch.assess(blindingLights, { ...autoMatch, title: "The Weeknd Lights loop", durationSeconds: 3600 }).verdict, "mismatch");
    assert.equal(VideoMatch.assess(blindingLights, { ...autoMatch, title: "Blinding Lights", durationSeconds: 30 }).verdict, "uncertain",
        "a full title match is kept, not rejected on length alone");
    assert.equal(VideoMatch.assess(blindingLights, { ...autoMatch, durationSeconds: 900 }).verdict, "uncertain",
        "without a title, a very long video may be a story-style music video");
    assert.equal(VideoMatch.compareLength(200_000, 202), "exact");
    assert.equal(VideoMatch.compareLength(200_000, 260), "longer");
    assert.equal(VideoMatch.compareLength(200_000, 100), "much-shorter");
    assert.equal(VideoMatch.compareLength(200_000, 0), "unknown");
});

test("keeps the server's pick unless it is wrong, skipping rejected videos", () => {
    const wrong = { ...autoMatch, youtubeVideoId: "wrong123456", title: "Dua Lipa - Levitating" };
    const right = { ...autoMatch, youtubeVideoId: "right123456", title: "Travis Scott - goosebumps (Official Video)" };
    const otherRight = { ...autoMatch, youtubeVideoId: "other123456", title: "goosebumps" };
    assert.equal(VideoMatch.pickCandidate(goosebumps, [wrong, right]).video, right);
    assert.equal(VideoMatch.pickCandidate(goosebumps, [otherRight, right]).video, otherRight);
    assert.equal(VideoMatch.pickCandidate(goosebumps, [right, otherRight], { rejectedIds: new Set(["right123456"]) }).video, otherRight);
    assert.equal(VideoMatch.pickCandidate(goosebumps, [wrong]), null);
});

test("rates how far the video timeline can be trusted", () => {
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: 37, isAutoGenerated: true }, 261, 200_040), "known");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: 0, isAutoGenerated: true }, 201, 200_040), "aligned");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: null, isAutoGenerated: true }, 261, 200_040), "guess");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: 0, isAutoGenerated: true }, 266, 311_866), "guess",
        "a shorter edit (Stronger: 4:26 video, 5:12 song) cannot follow the song from its start");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: 17, isAutoGenerated: true }, 305, 339_000), "edit",
        "a known start on a shorter edit (90210: 5:05 video, 5:39 song) holds only until the first cut");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: null }, 0, 200_040), "unknown");
    assert.equal(VideoMatch.getTimingConfidence({ captionStartTime: 0, isAutoGenerated: false }, 400, 200_040), "known",
        "a person-registered start at 0 is a real start point");
});
